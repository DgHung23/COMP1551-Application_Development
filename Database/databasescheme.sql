   11. Reference data required by the schema itself: the three roles.
       (Business sample data lives in sampledata.sql.)
   --------------------------------------------------------------------- */
INSERT INTO Roles (RoleId, RoleName, [Description]) VALUES
    (1, N'Performer', N'Artists and DJs performing at the festival'),
    (2, N'Crew',      N'Stage, sound, lighting, security staff and volunteers'),
    (3, N'Vendor',    N'Food and merchandise stall holders');
GO

PRINT 'MusicFestivalDB schema created successfully.';
