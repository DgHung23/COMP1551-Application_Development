/* =====================================================================
   COMP1551 Application Development - Coursework 2026/27
   Music Festival Operations System
   ---------------------------------------------------------------------
   databasescheme.sql
   Rebuilds the database from scratch: CREATE DATABASE, CREATE TABLE
   and all constraints (PK, FK, UNIQUE, NOT NULL, CHECK, DEFAULT).

   Target DBMS : Microsoft SQL Server 2022 (Docker image
                 mcr.microsoft.com/mssql/server:2022-latest)
   Run with    : SSMS / Azure Data Studio / VS SQL Server Object Explorer
                 or: sqlcmd -S localhost,1433 -U sa -P <pwd> -C -i databasescheme.sql

   Design summary (Table-Per-Type inheritance):
     Roles                 lookup of the three user groups (1,2,3)
     People                common fields of every person (super-type)
     Performers            Performer-specific fields  (sub-type, 1:1)
     CrewMembers           Crew-specific fields       (sub-type, 1:1)
     Vendors               Vendor-specific fields     (sub-type, 1:1)
     Genres                lookup of music genres
     PerformerGenres       link table  Performer  M:N  Genre
     ProductCategories     lookup of product categories
     VendorCategories      link table  Vendor     M:N  ProductCategory
   ===================================================================== */

USE master;
GO

/* ---------------------------------------------------------------------
   1. Drop the database if it already exists so the script is re-runnable.
      SINGLE_USER + ROLLBACK IMMEDIATE closes any open connections first.
   --------------------------------------------------------------------- */
IF DB_ID(N'MusicFestivalDB') IS NOT NULL
BEGIN
    ALTER DATABASE MusicFestivalDB SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE MusicFestivalDB;
END
GO

/* ---------------------------------------------------------------------
   2. CREATE DATABASE
   --------------------------------------------------------------------- */
CREATE DATABASE MusicFestivalDB;
GO

USE MusicFestivalDB;
GO

/* ---------------------------------------------------------------------
   3. Roles - fixed lookup table for the three user groups.
      The Id values mirror the C# enum PersonRole (1 = Performer,
      2 = Crew, 3 = Vendor) so they are NOT identity columns.
   --------------------------------------------------------------------- */
CREATE TABLE Roles (
    RoleId        INT            NOT NULL,
    RoleName      NVARCHAR(20)   NOT NULL,
    [Description] NVARCHAR(200)  NULL,
    CONSTRAINT PK_Roles          PRIMARY KEY (RoleId),
    CONSTRAINT UQ_Roles_RoleName UNIQUE (RoleName),
    CONSTRAINT CK_Roles_RoleId   CHECK (RoleId IN (1, 2, 3))
);
GO

/* ---------------------------------------------------------------------
   4. People - super-type table holding the common fields of all roles.
      * PersonId is a surrogate key generated by IDENTITY.
      * Email is UNIQUE: a new person cannot be added if the email
        already exists (also enforced in the Business layer).
      * UQ_People_PersonId_RoleId lets each sub-type table reference
        (PersonId, RoleId) so a person can only ever have the sub-type
        row that matches his/her role (see Performers below).
      * IsDeleted / DeletedAt support the soft-delete + restore extension.
      * All date/time columns are stored in UTC (SYSUTCDATETIME) and converted
        to local time by the application, whatever the server time zone is.
   --------------------------------------------------------------------- */
CREATE TABLE People (
    PersonId   INT            IDENTITY(1,1) NOT NULL,
    FullName   NVARCHAR(100)  NOT NULL,
    Telephone  VARCHAR(20)    NOT NULL,
    Email      VARCHAR(254)   NOT NULL,
    RoleId     INT            NOT NULL,
    IsDeleted  BIT            NOT NULL CONSTRAINT DF_People_IsDeleted DEFAULT (0),
    CreatedAt  DATETIME2(0)   NOT NULL CONSTRAINT DF_People_CreatedAt DEFAULT (SYSUTCDATETIME()),
    UpdatedAt  DATETIME2(0)   NULL,
    DeletedAt  DATETIME2(0)   NULL,
    CONSTRAINT PK_People                 PRIMARY KEY (PersonId),
    CONSTRAINT UQ_People_Email           UNIQUE (Email),
    CONSTRAINT UQ_People_PersonId_RoleId UNIQUE (PersonId, RoleId),
    CONSTRAINT FK_People_Roles           FOREIGN KEY (RoleId) REFERENCES Roles (RoleId),
    CONSTRAINT CK_People_FullName        CHECK (LEN(LTRIM(RTRIM(FullName))) > 0),
    CONSTRAINT CK_People_Email           CHECK (Email LIKE '%_@_%._%'),
    CONSTRAINT CK_People_Telephone       CHECK (LEN(Telephone) >= 8)
);
GO

/* ---------------------------------------------------------------------
   5. Performers - sub-type (artists / DJs).
      RoleId is fixed to 1 by a CHECK and, together with PersonId, is a
      composite FK to People. Therefore only a person whose role is
      Performer can own a Performers row. ON DELETE CASCADE removes the
      row automatically when the person is permanently deleted.
   --------------------------------------------------------------------- */
CREATE TABLE Performers (
    PersonId  INT            NOT NULL,
    RoleId    INT            NOT NULL CONSTRAINT DF_Performers_RoleId DEFAULT (1),
    Fee       DECIMAL(12,2)  NOT NULL,
    CONSTRAINT PK_Performers        PRIMARY KEY (PersonId),
    CONSTRAINT CK_Performers_RoleId CHECK (RoleId = 1),
    CONSTRAINT CK_Performers_Fee    CHECK (Fee >= 0),
    CONSTRAINT FK_Performers_People FOREIGN KEY (PersonId, RoleId)
        REFERENCES People (PersonId, RoleId) ON DELETE CASCADE
);
GO

/* ---------------------------------------------------------------------
   6. CrewMembers - sub-type (stage / sound / lighting / security /
      volunteers). The CHECK constraint mirrors the business rule:
        FullTime : 25 - 40 weekly hours
        PartTime :  1 - 24 weekly hours
   --------------------------------------------------------------------- */
CREATE TABLE CrewMembers (
    PersonId        INT           NOT NULL,
    RoleId          INT           NOT NULL CONSTRAINT DF_CrewMembers_RoleId DEFAULT (2),
    HourlyRate      DECIMAL(8,2)  NOT NULL,
    EmploymentType  VARCHAR(10)   NOT NULL,
    WeeklyHours     INT           NOT NULL,
    CONSTRAINT PK_CrewMembers                PRIMARY KEY (PersonId),
    CONSTRAINT CK_CrewMembers_RoleId         CHECK (RoleId = 2),
    CONSTRAINT CK_CrewMembers_HourlyRate     CHECK (HourlyRate > 0),
    CONSTRAINT CK_CrewMembers_EmploymentType CHECK (EmploymentType IN ('FullTime', 'PartTime')),
    CONSTRAINT CK_CrewMembers_WeeklyHours    CHECK (
           (EmploymentType = 'FullTime' AND WeeklyHours BETWEEN 25 AND 40)
        OR (EmploymentType = 'PartTime' AND WeeklyHours BETWEEN 1  AND 24)),
    CONSTRAINT FK_CrewMembers_People FOREIGN KEY (PersonId, RoleId)
        REFERENCES People (PersonId, RoleId) ON DELETE CASCADE
);
GO

/* ---------------------------------------------------------------------
   7. Vendors - sub-type (food / merch stalls).
      StallName is the vendor (business) name, separate from the
      contact person's FullName held in People.
   --------------------------------------------------------------------- */
CREATE TABLE Vendors (
    PersonId   INT            NOT NULL,
    RoleId     INT            NOT NULL CONSTRAINT DF_Vendors_RoleId DEFAULT (3),
    StallName  NVARCHAR(100)  NOT NULL,
    CONSTRAINT PK_Vendors           PRIMARY KEY (PersonId),
    CONSTRAINT CK_Vendors_RoleId    CHECK (RoleId = 3),
    CONSTRAINT CK_Vendors_StallName CHECK (LEN(LTRIM(RTRIM(StallName))) > 0),
    CONSTRAINT FK_Vendors_People    FOREIGN KEY (PersonId, RoleId)
        REFERENCES People (PersonId, RoleId) ON DELETE CASCADE
);
GO

/* ---------------------------------------------------------------------
   8. Genres lookup + PerformerGenres link table (M:N).
      Composite PK (PersonId, GenreId) stops the same genre being linked
      twice to one performer.
   --------------------------------------------------------------------- */
CREATE TABLE Genres (
    GenreId    INT           IDENTITY(1,1) NOT NULL,
    GenreName  NVARCHAR(50)  NOT NULL,
    CONSTRAINT PK_Genres           PRIMARY KEY (GenreId),
    CONSTRAINT UQ_Genres_GenreName UNIQUE (GenreName)
);
GO

CREATE TABLE PerformerGenres (
    PersonId  INT  NOT NULL,
    GenreId   INT  NOT NULL,
    CONSTRAINT PK_PerformerGenres            PRIMARY KEY (PersonId, GenreId),
    CONSTRAINT FK_PerformerGenres_Performers FOREIGN KEY (PersonId)
        REFERENCES Performers (PersonId) ON DELETE CASCADE,
    CONSTRAINT FK_PerformerGenres_Genres     FOREIGN KEY (GenreId)
        REFERENCES Genres (GenreId)
);
GO

/* ---------------------------------------------------------------------
   9. ProductCategories lookup + VendorCategories link table (M:N).
   --------------------------------------------------------------------- */
CREATE TABLE ProductCategories (
    CategoryId    INT           IDENTITY(1,1) NOT NULL,
    CategoryName  NVARCHAR(50)  NOT NULL,
    CONSTRAINT PK_ProductCategories              PRIMARY KEY (CategoryId),
    CONSTRAINT UQ_ProductCategories_CategoryName UNIQUE (CategoryName)
);
GO

CREATE TABLE VendorCategories (
    PersonId    INT  NOT NULL,
    CategoryId  INT  NOT NULL,
    CONSTRAINT PK_VendorCategories                   PRIMARY KEY (PersonId, CategoryId),
    CONSTRAINT FK_VendorCategories_Vendors           FOREIGN KEY (PersonId)
        REFERENCES Vendors (PersonId) ON DELETE CASCADE,
    CONSTRAINT FK_VendorCategories_ProductCategories FOREIGN KEY (CategoryId)
        REFERENCES ProductCategories (CategoryId)
);
GO

/* ---------------------------------------------------------------------
   10. Indexes to speed up the most common look-ups
       (filter by role, list active records, search by name).
   --------------------------------------------------------------------- */
CREATE INDEX IX_People_RoleId_IsDeleted ON People (RoleId, IsDeleted);
CREATE INDEX IX_People_FullName         ON People (FullName);
CREATE INDEX IX_PerformerGenres_GenreId ON PerformerGenres (GenreId);
CREATE INDEX IX_VendorCategories_CatId  ON VendorCategories (CategoryId);
GO

