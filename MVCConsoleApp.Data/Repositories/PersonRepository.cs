using Microsoft.Data.SqlClient;
using MVCConsoleApp.Data.Entities;

namespace MVCConsoleApp.Data.Repositories
{
    /// <summary>
    /// DATA ACCESS LAYER - SQL Server implementation of <see cref="IPersonRepository"/>.
    /// <para>
    /// This is the ONLY place where SQL for people is written. Every statement uses
    /// parameters (<c>@name</c>) - user input is never concatenated into SQL - which protects
    /// the application against SQL injection. Inserts and updates that touch several tables
    /// run inside a <see cref="SqlTransaction"/> so a record is either saved completely or not at all.
    /// </para>
    /// </summary>
    public class PersonRepository : RepositoryBase, IPersonRepository
    {
        // Separator used by STRING_AGG to return several genres / categories in one column.
        // The Business layer does not allow this character inside a genre or category name.
        private const char ListSeparator = '|';

        // One SELECT shared by every "read" method. LEFT JOINs bring the role-specific columns;
        // only the columns of the person's own role are filled, the others are NULL.
        // The two sub-queries aggregate the M:N link tables into a single text column.
        private const string SelectPeopleSql =
            "SELECT p.PersonId, p.FullName, p.Telephone, p.Email, p.RoleId, p.IsDeleted, p.DeletedAt, " +
            "       pf.Fee, c.HourlyRate, c.EmploymentType, c.WeeklyHours, v.StallName, " +
            "       (SELECT STRING_AGG(g.GenreName, '|') WITHIN GROUP (ORDER BY g.GenreName) " +
            "          FROM PerformerGenres pg INNER JOIN Genres g ON g.GenreId = pg.GenreId " +
            "         WHERE pg.PersonId = p.PersonId) AS Genres, " +
            "       (SELECT STRING_AGG(pc.CategoryName, '|') WITHIN GROUP (ORDER BY pc.CategoryName) " +
            "          FROM VendorCategories vc INNER JOIN ProductCategories pc ON pc.CategoryId = vc.CategoryId " +
            "         WHERE vc.PersonId = p.PersonId) AS Categories " +
            "FROM People p " +
            "LEFT JOIN Performers  pf ON pf.PersonId = p.PersonId " +
            "LEFT JOIN CrewMembers c  ON c.PersonId  = p.PersonId " +
            "LEFT JOIN Vendors     v  ON v.PersonId  = p.PersonId ";

        // ================================ CREATE ================================

        /// <summary>
        /// Inserts a new person. The common fields go to <c>People</c>; the role-specific fields go
        /// to the matching sub-type table and link tables. Everything runs in one transaction.
        /// </summary>
        /// <param name="person">Validated person to insert (Performer, CrewMember or Vendor).</param>
        /// <returns>The PersonID generated by the database.</returns>
        public int Create(Person person)
        {
            try
            {
                using (SqlConnection connection = OpenConnection())
                // One connection + one transaction for the whole insert: People, the sub-type
                // table and the link tables are written together or not at all.
                using (SqlTransaction transaction = connection.BeginTransaction())
                {
                    try
                    {
                        // 1) Common fields. OUTPUT INSERTED.PersonId returns the new identity value.
                        string sql = "INSERT INTO People (FullName, Telephone, Email, RoleId) " +
                                     "OUTPUT INSERTED.PersonId " +
                                     "VALUES (@fullName, @telephone, @email, @roleId)";
                        int newId;
                        using (SqlCommand command = new SqlCommand(sql, connection, transaction))
                        {
                            AddCommonParameters(command, person);
                            newId = (int)command.ExecuteScalar();
                        }

                        // 2) Role-specific fields (sub-type table + link tables).
                        InsertRoleDetails(connection, transaction, newId, person);

                        // Every statement succeeded: make the changes permanent.
                        transaction.Commit();
                        person.PersonId = newId;
                        return newId;
                    }
                    catch
                    {
                        // Undo the partial insert, then let the outer catch wrap the error.
                        transaction.Rollback();
                        throw;
                    }
                }
            }
            catch (SqlException ex)
            {
                throw Wrap("adding a person", ex);
            }
        }

        // ================================= READ =================================

        /// <summary>Returns all active people ordered by PersonID.</summary>
        public List<Person> GetAll()
        {
            // Active records only, in PersonID order.
            return Query("WHERE p.IsDeleted = 0 ORDER BY p.PersonId", "loading all people", null);
        }

        /// <summary>Returns all active people of one role, ordered by PersonID.</summary>
        /// <param name="role">Role to filter by.</param>
        public List<Person> GetByRole(PersonRole role)
        {
            return Query("WHERE p.IsDeleted = 0 AND p.RoleId = @roleId ORDER BY p.PersonId",
                         "loading people by role",
                         command => command.Parameters.AddWithValue("@roleId", (int)role));
        }

        /// <summary>Finds one person by PersonID.</summary>
        /// <param name="personId">ID to look for.</param>
        /// <param name="includeDeleted">True to also search the recycle bin.</param>
        /// <returns>The person, or null when not found.</returns>
        public Person? GetById(int personId, bool includeDeleted = false)
        {
            // Normally only active records are found; restore / permanent delete also
            // need to find records that are in the recycle bin.
            string where = includeDeleted
                ? "WHERE p.PersonId = @id"
                : "WHERE p.PersonId = @id AND p.IsDeleted = 0";
            return Query(where, "loading a person",
                         command => command.Parameters.AddWithValue("@id", personId))
                   .FirstOrDefault();
        }

        /// <summary>Finds the person (active or deleted) that owns an email address.</summary>
        /// <param name="email">Email to look for (comparison is case-insensitive).</param>
        /// <returns>The owner, or null when the email is free.</returns>
        public Person? GetByEmail(string email)
        {
            // LOWER() + lower-case parameter guarantees a case-insensitive match even if the
            // database was created with a case-sensitive collation.
            return Query("WHERE LOWER(p.Email) = @email", "checking an email address",
                         command => command.Parameters.AddWithValue("@email", email.Trim().ToLowerInvariant()))
                   .FirstOrDefault();
        }

        /// <summary>Partial-match search on name or email (extension feature).</summary>
        /// <param name="term">Text to look for anywhere in the name or email.</param>
        public List<Person> Search(string term)
        {
            // The term is wrapped in % wildcards for a "contains" search; EscapeLike makes
            // sure % or _ typed by the user are treated as normal characters.
            return Query("WHERE p.IsDeleted = 0 AND (p.FullName LIKE @term OR p.Email LIKE @term) ORDER BY p.PersonId",
                         "searching people",
                         command => command.Parameters.AddWithValue("@term", "%" + EscapeLike(term.Trim()) + "%"));
        }

        /// <summary>Returns the recycle bin: all soft-deleted people, most recently deleted first.</summary>
        public List<Person> GetDeleted()
        {
            // Most recently deleted first.
            return Query("WHERE p.IsDeleted = 1 ORDER BY p.DeletedAt DESC", "loading the recycle bin", null);
        }

        // ================================ UPDATE ================================

        /// <summary>
        /// Updates an active person. Because the role may change (e.g. a Crew member becomes a
        /// Vendor), the old role-specific rows are removed and the new ones inserted, all inside
        /// one transaction.
        /// </summary>
        /// <param name="person">Person with the new values; <see cref="Person.PersonId"/> identifies the record.</param>
        /// <returns>True when updated; false when no active person has that ID.</returns>
        public bool Update(Person person)
        {
            try
            {
                using (SqlConnection connection = OpenConnection())
                // The four steps below run in ONE transaction, so a failure in any step
                // (e.g. a CHECK constraint) leaves the original record untouched.
                using (SqlTransaction transaction = connection.BeginTransaction())
                {
                    try
                    {
                        // 1) Make sure the record exists and is active (this also locks the row).
                        string checkSql = "UPDATE People SET UpdatedAt = SYSUTCDATETIME() WHERE PersonId = @id AND IsDeleted = 0";
                        using (SqlCommand check = new SqlCommand(checkSql, connection, transaction))
                        {
                            check.Parameters.AddWithValue("@id", person.PersonId);
                            if (check.ExecuteNonQuery() == 0)
                            {
                                transaction.Rollback();
                                return false;   // ID not found -> handled gracefully by the caller
                            }
                        }

                        // 2) Remove the old role-specific rows (link tables cascade automatically).
                        //    This must happen before RoleId changes because of the composite FKs.
                        string deleteDetailsSql = "DELETE FROM Performers  WHERE PersonId = @id; " +
                                                  "DELETE FROM CrewMembers WHERE PersonId = @id; " +
                                                  "DELETE FROM Vendors     WHERE PersonId = @id;";
                        using (SqlCommand deleteDetails = new SqlCommand(deleteDetailsSql, connection, transaction))
                        {
                            deleteDetails.Parameters.AddWithValue("@id", person.PersonId);
                            deleteDetails.ExecuteNonQuery();
                        }

                        // 3) Update the common fields (including the possibly new role).
                        string updateSql = "UPDATE People SET FullName = @fullName, Telephone = @telephone, " +
                                           "Email = @email, RoleId = @roleId WHERE PersonId = @id";
                        using (SqlCommand update = new SqlCommand(updateSql, connection, transaction))
                        {
                            update.Parameters.AddWithValue("@id", person.PersonId);
                            AddCommonParameters(update, person);
                            update.ExecuteNonQuery();
                        }

                        // 4) Insert the role-specific rows again with the new values.
                        InsertRoleDetails(connection, transaction, person.PersonId, person);

                        transaction.Commit();
                        return true;
                    }
                    catch
                    {
                        transaction.Rollback();
                        throw;
                    }
                }
            }
            catch (SqlException ex)
            {
                throw Wrap("updating a person", ex);
            }
        }

        // ============================ DELETE / RESTORE ============================

        /// <summary>Soft delete: marks the person as deleted so it can be restored later.</summary>
        /// <param name="personId">ID of an active person.</param>
        /// <returns>True when deleted; false when no active person has that ID.</returns>
        public bool SoftDelete(int personId)
        {
            return ExecuteNonQuery(
                "UPDATE People SET IsDeleted = 1, DeletedAt = SYSUTCDATETIME() WHERE PersonId = @id AND IsDeleted = 0",
                personId, "deleting a person");
        }

        /// <summary>Restores a person from the recycle bin.</summary>
        /// <param name="personId">ID of a soft-deleted person.</param>
        /// <returns>True when restored; false when the recycle bin does not contain that ID.</returns>
        public bool Restore(int personId)
        {
            return ExecuteNonQuery(
                "UPDATE People SET IsDeleted = 0, DeletedAt = NULL WHERE PersonId = @id AND IsDeleted = 1",
                personId, "restoring a person");
        }

        /// <summary>
        /// Permanently removes a person that is already in the recycle bin.
        /// ON DELETE CASCADE removes the role-specific and link rows automatically.
        /// </summary>
        /// <param name="personId">ID of a soft-deleted person.</param>
        /// <returns>True when removed; false when the recycle bin does not contain that ID.</returns>
        public bool HardDelete(int personId)
        {
            return ExecuteNonQuery(
                "DELETE FROM People WHERE PersonId = @id AND IsDeleted = 1",
                personId, "permanently deleting a person");
        }

        // ============================ Private helpers ============================

        /// <summary>Runs the shared SELECT with an extra WHERE/ORDER BY clause and maps every row.</summary>
        /// <param name="whereClause">Fixed SQL text written in this class (never user input).</param>
        /// <param name="operation">Description used in error messages.</param>
        /// <param name="addParameters">Optional callback that adds the parameters used by the clause.</param>
        private List<Person> Query(string whereClause, string operation, Action<SqlCommand>? addParameters)
        {
            var result = new List<Person>();
            try
            {
                using (SqlConnection connection = OpenConnection())
                // The shared SELECT + the caller's clause; parameters are added by the callback.
                using (SqlCommand command = new SqlCommand(SelectPeopleSql + whereClause, connection))
                {
                    addParameters?.Invoke(command);
                    using (SqlDataReader reader = command.ExecuteReader())
                    {
                        // Every row becomes the right sub-class of Person (see MapPerson).
                        while (reader.Read())
                        {
                            result.Add(MapPerson(reader));
                        }
                    }
                }
            }
            catch (SqlException ex)
            {
                throw Wrap(operation, ex);
            }
            return result;
        }

        /// <summary>Executes an UPDATE/DELETE that takes only a PersonID and reports whether a row changed.</summary>
        private bool ExecuteNonQuery(string sql, int personId, string operation)
        {
            try
            {
                using (SqlConnection connection = OpenConnection())
                using (SqlCommand command = new SqlCommand(sql, connection))
                {
                    command.Parameters.AddWithValue("@id", personId);
                    // ExecuteNonQuery returns the number of rows changed: 0 means "ID not found".
                    return command.ExecuteNonQuery() > 0;
                }
            }
            catch (SqlException ex)
            {
                throw Wrap(operation, ex);
            }
        }

        /// <summary>Adds the parameters for the common People columns.</summary>
        private static void AddCommonParameters(SqlCommand command, Person person)
        {
            command.Parameters.AddWithValue("@fullName", person.FullName);
            command.Parameters.AddWithValue("@telephone", person.Telephone);
            command.Parameters.AddWithValue("@email", person.Email);
            command.Parameters.AddWithValue("@roleId", (int)person.Role);
        }

        /// <summary>
        /// Inserts the sub-type row and link rows that belong to the person's role.
        /// C# pattern matching selects the right branch from the run-time type of the object.
        /// </summary>
        private static void InsertRoleDetails(SqlConnection connection, SqlTransaction transaction, int personId, Person person)
        {
            switch (person)
            {
                case Performer performer:
                    using (SqlCommand command = new SqlCommand(
                        "INSERT INTO Performers (PersonId, Fee) VALUES (@id, @fee)", connection, transaction))
                    {
                        command.Parameters.AddWithValue("@id", personId);
                        command.Parameters.AddWithValue("@fee", performer.Fee);
                        command.ExecuteNonQuery();
                    }
                    InsertLinks(connection, transaction, personId, performer.Genres,
                                "Genres", "GenreId", "GenreName", "PerformerGenres");
                    break;

                case CrewMember crew:
                    using (SqlCommand command = new SqlCommand(
                        "INSERT INTO CrewMembers (PersonId, HourlyRate, EmploymentType, WeeklyHours) " +
                        "VALUES (@id, @rate, @type, @hours)", connection, transaction))
                    {
                        command.Parameters.AddWithValue("@id", personId);
                        command.Parameters.AddWithValue("@rate", crew.HourlyRate);
                        command.Parameters.AddWithValue("@type", crew.EmploymentType.ToString());
                        command.Parameters.AddWithValue("@hours", crew.WeeklyHours);
                        command.ExecuteNonQuery();
                    }
                    break;

                case Vendor vendor:
                    using (SqlCommand command = new SqlCommand(
                        "INSERT INTO Vendors (PersonId, StallName) VALUES (@id, @stallName)", connection, transaction))
                    {
                        command.Parameters.AddWithValue("@id", personId);
                        command.Parameters.AddWithValue("@stallName", vendor.StallName);
                        command.ExecuteNonQuery();
                    }
                    InsertLinks(connection, transaction, personId, vendor.ProductCategories,
                                "ProductCategories", "CategoryId", "CategoryName", "VendorCategories");
                    break;

                default:
                    throw new NotSupportedException($"Unknown person type: {person.GetType().Name}");
            }
        }

        /// <summary>
        /// Links a person to several lookup values (genres or categories). A value that does not
        /// exist yet in the lookup table is created first ("get or create"), so users can type a new
        /// genre or category without leaving the add/edit screen.
        /// </summary>
        /// <param name="lookupTable">Lookup table name - a constant from this class, never user input.</param>
        /// <param name="idColumn">Primary key column of the lookup table.</param>
        /// <param name="nameColumn">Name column of the lookup table.</param>
        /// <param name="linkTable">Link (junction) table name.</param>
        private static void InsertLinks(SqlConnection connection, SqlTransaction transaction, int personId,
                                        IEnumerable<string> names, string lookupTable, string idColumn,
                                        string nameColumn, string linkTable)
        {
            string sql =
                $"DECLARE @lookupId INT = (SELECT {idColumn} FROM {lookupTable} WHERE {nameColumn} = @name); " +
                "IF @lookupId IS NULL " +
                "BEGIN " +
                $"    INSERT INTO {lookupTable} ({nameColumn}) VALUES (@name); " +
                "    SET @lookupId = CAST(SCOPE_IDENTITY() AS INT); " +
                "END " +
                $"INSERT INTO {linkTable} (PersonId, {idColumn}) VALUES (@personId, @lookupId);";

            // One small batch per name: find-or-create the lookup row, then link it.
            foreach (string name in names)
            {
                using (SqlCommand command = new SqlCommand(sql, connection, transaction))
                {
                    command.Parameters.AddWithValue("@name", name);
                    command.Parameters.AddWithValue("@personId", personId);
                    command.ExecuteNonQuery();
                }
            }
        }

        /// <summary>
        /// Converts one row of <see cref="SelectPeopleSql"/> into the correct sub-class.
        /// This is a small "factory": the RoleId column decides which concrete type is created,
        /// and the rest of the application only sees the abstract <see cref="Person"/> type.
        /// </summary>
        private static Person MapPerson(SqlDataReader reader)
        {
            // RoleId (1, 2 or 3) maps directly onto the PersonRole enum.
            PersonRole role = (PersonRole)reader.GetInt32(reader.GetOrdinal("RoleId"));

            Person person;
            switch (role)
            {
                case PersonRole.Performer:
                    // Performer columns: the fee + the aggregated list of genres.
                    var performer = new Performer
                    {
                        Fee = GetDecimalOrZero(reader, "Fee")
                    };
                    performer.SetGenres(SplitList(reader, "Genres"));
                    person = performer;
                    break;

                case PersonRole.Crew:
                    // Crew columns are read only when present (they are NULL for other roles).
                    var crew = new CrewMember();
                    int typeOrdinal = reader.GetOrdinal("EmploymentType");
                    if (!reader.IsDBNull(typeOrdinal))
                    {
                        crew.HourlyRate = reader.GetDecimal(reader.GetOrdinal("HourlyRate"));
                        crew.EmploymentType = Enum.Parse<EmploymentType>(reader.GetString(typeOrdinal));
                        crew.WeeklyHours = reader.GetInt32(reader.GetOrdinal("WeeklyHours"));
                    }
                    person = crew;
                    break;

                case PersonRole.Vendor:
                    // Vendor columns: stall name + the aggregated list of categories.
                    var vendor = new Vendor();
                    int stallOrdinal = reader.GetOrdinal("StallName");
                    if (!reader.IsDBNull(stallOrdinal))
                    {
                        vendor.StallName = reader.GetString(stallOrdinal);
                    }
                    vendor.SetProductCategories(SplitList(reader, "Categories"));
                    person = vendor;
                    break;

                default:
                    throw new DataAccessException($"Unknown RoleId {(int)role} in the database.");
            }

            // Common fields are filled the same way for every role.
            // GetOrdinal finds a column by name, so the code does not depend on column order.
            person.PersonId = reader.GetInt32(reader.GetOrdinal("PersonId"));
            person.FullName = reader.GetString(reader.GetOrdinal("FullName"));
            person.Telephone = reader.GetString(reader.GetOrdinal("Telephone"));
            person.Email = reader.GetString(reader.GetOrdinal("Email"));
            person.IsDeleted = reader.GetBoolean(reader.GetOrdinal("IsDeleted"));
            int deletedAtOrdinal = reader.GetOrdinal("DeletedAt");
            // Dates are stored in UTC; convert to the user's local time for display.
            person.DeletedAt = reader.IsDBNull(deletedAtOrdinal)
                ? null
                : DateTime.SpecifyKind(reader.GetDateTime(deletedAtOrdinal), DateTimeKind.Utc).ToLocalTime();
            return person;
        }

        /// <summary>Reads a nullable DECIMAL column, returning 0 when it is NULL.</summary>
        private static decimal GetDecimalOrZero(SqlDataReader reader, string column)
        {
            int ordinal = reader.GetOrdinal(column);
            return reader.IsDBNull(ordinal) ? 0m : reader.GetDecimal(ordinal);
        }

        /// <summary>Splits a STRING_AGG column ("Pop|Indie") back into a list of names.</summary>
        private static List<string> SplitList(SqlDataReader reader, string column)
        {
            int ordinal = reader.GetOrdinal(column);
            if (reader.IsDBNull(ordinal))
            {
                return new List<string>();
            }
            return reader.GetString(ordinal).Split(ListSeparator, StringSplitOptions.RemoveEmptyEntries).ToList();
        }
    }
