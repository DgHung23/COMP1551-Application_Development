using System.Globalization;

namespace MVCConsoleApp.Data.Entities
{
    /// <summary>
    /// MODEL (MVC) - abstract base class for every person involved in delivering the festival.
    /// <para>
    /// OOP principles demonstrated here:
    /// <list type="bullet">
    /// <item><b>Abstraction</b> - <see cref="Person"/> cannot be instantiated; it only describes what
    /// all roles have in common.</item>
    /// <item><b>Encapsulation</b> - every common field is a <c>private</c> backing field that can only be
    /// changed through a property setter which validates and normalises the value.</item>
    /// <item><b>Inheritance</b> - <see cref="Performer"/>, <see cref="CrewMember"/> and <see cref="Vendor"/>
    /// derive from this class and inherit the common fields.</item>
    /// <item><b>Polymorphism</b> - <see cref="Role"/>, <see cref="DescribeRoleFields"/> and
    /// <see cref="EstimateCost"/> are abstract and overridden by each sub-class, so the rest of the
    /// application can treat any person uniformly (e.g. <c>List&lt;Person&gt;</c>).</item>
    /// </list>
    /// </para>
    /// </summary>
    public abstract class Person
    {
        /// <summary>Maximum length of <see cref="FullName"/> (matches NVARCHAR(100) in the database).</summary>
        public const int MaxNameLength = 100;

        /// <summary>Maximum length of <see cref="Telephone"/> (matches VARCHAR(20) in the database).</summary>
        public const int MaxTelephoneLength = 20;

        /// <summary>Maximum length of <see cref="Email"/> (matches VARCHAR(254) in the database).</summary>
        public const int MaxEmailLength = 254;

        // ===================== Private fields (encapsulation) =====================
        private int _personId;
        private string _fullName = string.Empty;
        private string _telephone = string.Empty;
        private string _email = string.Empty;

        /// <summary>Parameterless constructor used when an object is materialised from the database.</summary>
        protected Person()
        {
        }

        /// <summary>
        /// Constructor used by sub-classes to initialise the common fields in one step.
        /// The values go through the validating property setters.
        /// </summary>
        /// <param name="fullName">Full name of the person.</param>
        /// <param name="telephone">Telephone number.</param>
        /// <param name="email">Email address (must be unique in the system).</param>
        protected Person(string fullName, string telephone, string email)
        {
            FullName = fullName;
            Telephone = telephone;
            Email = email;
        }

        // ============================ Common properties ============================

        /// <summary>
        /// Gets or sets the unique identifier (PersonID). It is generated by the database,
        /// so it is 0 for a person that has not been saved yet. Negative values are rejected.
        /// </summary>
        public int PersonId
        {
            get => _personId;
            set
            {
                if (value < 0)
                {
                    throw new ArgumentOutOfRangeException(nameof(PersonId), "PersonID cannot be negative.");
                }
                _personId = value;
            }
        }

        /// <summary>
        /// Gets or sets the full name. The setter rejects empty names and names longer than
        /// <see cref="MaxNameLength"/>, and removes leading/trailing spaces.
        /// </summary>
        public string FullName
        {
            get => _fullName;
            set => _fullName = RequireText(value, "Name", MaxNameLength);
        }

        /// <summary>
        /// Gets or sets the telephone number. Spaces, dashes and brackets are removed so that numbers such as
        /// "07700 900-101" and "07700900101" are stored in the same way.
        /// </summary>
        public string Telephone
        {
            get => _telephone;
            set
            {
                // Normalise first, then check that something meaningful is left.
                string normalised = new string((value ?? string.Empty).Where(c => !char.IsWhiteSpace(c) && c != '-' && c != '(' && c != ')').ToArray());
                _telephone = RequireText(normalised, "Telephone", MaxTelephoneLength);
            }
        }

        /// <summary>
        /// Gets or sets the email address. It is trimmed and stored in lower case, which makes the
        /// "email must be unique" rule case-insensitive (Luna@x.com and luna@x.com are the same).
        /// </summary>
        public string Email
        {
            get => _email;
            set => _email = RequireText(value, "Email", MaxEmailLength).ToLowerInvariant();
        }

        /// <summary>Gets a value indicating whether the record is in the recycle bin (soft-deleted).</summary>
        public bool IsDeleted { get; set; }

        /// <summary>Gets or sets the date/time the record was soft-deleted (null when active).</summary>
        public DateTime? DeletedAt { get; set; }

        // ===================== Polymorphic members (overridden) =====================

        /// <summary>
        /// Gets the role of this person. Each sub-class returns its own fixed value,
        /// so the role can never be inconsistent with the object's type.
        /// </summary>
        public abstract PersonRole Role { get; }

        /// <summary>
        /// Returns the role-specific fields as label/value pairs, e.g. ("Fee", "£12,000.00").
        /// Views use this to print the details of ANY person without knowing its concrete type.
        /// </summary>
        public abstract IReadOnlyList<KeyValuePair<string, string>> DescribeRoleFields();

        /// <summary>
        /// Estimates how much this person costs the festival (used by the cost report).
        /// Performers cost their fee, crew cost hourly rate x weekly hours, vendors cost nothing.
        /// </summary>
        public abstract decimal EstimateCost();

        // ================= Read-only helpers (useful for data binding) =================

        /// <summary>Gets the role as text, e.g. "Performer" (used by grid columns).</summary>
        public string RoleName => Role.ToString();

        /// <summary>Gets a one-line summary of the role-specific fields (used in tables and grids).</summary>
        public string RoleDetails => string.Join("; ", DescribeRoleFields().Select(pair => pair.Value));

        /// <summary>Gets the estimated cost formatted as money (used in tables and grids).</summary>
        public string EstimatedCostText => FormatMoney(EstimateCost());

        /// <summary>Returns a readable one-line description of the person (overrides <see cref="object.ToString"/>).</summary>
        public override string ToString()
        {
            return $"#{PersonId} {FullName} [{Role}] {Email}, {Telephone} | {RoleDetails}";
        }

        // ============================== Shared helpers ==============================

        /// <summary>
        /// Formats an amount of money in pounds sterling with two decimals, e.g. £1,250.50.
        /// InvariantCulture is used so the output is the same on every computer.
        /// </summary>
        /// <param name="amount">Amount to format.</param>
        /// <returns>The formatted amount.</returns>
        public static string FormatMoney(decimal amount)
        {
            return "£" + amount.ToString("N2", CultureInfo.InvariantCulture);
        }

        /// <summary>
        /// Guard used by setters of this class and its sub-classes: the text must not be empty
        /// and must not exceed <paramref name="maxLength"/> characters.
        /// </summary>
        /// <param name="value">Value to check.</param>
        /// <param name="fieldName">Friendly field name used in the error message.</param>
        /// <param name="maxLength">Maximum allowed length.</param>
        /// <returns>The trimmed value.</returns>
        /// <exception cref="ArgumentException">Thrown when the value is empty or too long.</exception>
        protected static string RequireText(string? value, string fieldName, int maxLength)
        {
            string trimmed = (value ?? string.Empty).Trim();
            if (trimmed.Length == 0)
            {
                throw new ArgumentException($"{fieldName} cannot be empty.", fieldName);
            }
            if (trimmed.Length > maxLength)
            {
                throw new ArgumentException($"{fieldName} cannot be longer than {maxLength} characters.", fieldName);
            }
            return trimmed;
        }

        /// <summary>
        /// Cleans a list of names (genres or categories): trims each item, removes blanks and
        /// removes duplicates ignoring case. Shared by <see cref="Performer"/> and <see cref="Vendor"/>.
        /// </summary>
        /// <param name="items">Raw names entered by the user.</param>
        /// <returns>A clean, duplicate-free list.</returns>
        protected static List<string> CleanNameList(IEnumerable<string>? items)
        {
            var result = new List<string>();
            foreach (string item in items ?? Enumerable.Empty<string>())
            {
                string trimmed = (item ?? string.Empty).Trim();
                bool alreadyAdded = result.Any(existing => string.Equals(existing, trimmed, StringComparison.OrdinalIgnoreCase));
                if (trimmed.Length > 0 && !alreadyAdded)
                {
                    result.Add(trimmed);
                }
            }
            return result;
        }
    }
}
